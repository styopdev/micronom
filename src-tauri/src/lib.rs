
use std::net::TcpListener;
use std::path::{Path, PathBuf};

fn write_file(
    service_dir: &Path,
    relative_path: &str,
    contents: &str,
) -> Result<(), String> {
    let path = service_dir.join(relative_path);

    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("Could not create directory: {e}"))?;
    }

    std::fs::write(&path, contents)
        .map_err(|e| format!("Could not write {}: {e}", relative_path))
}

fn find_available_port() -> Result<u16, String> {
    let listener = TcpListener::bind(("127.0.0.1", 0))
        .map_err(|e| format!("Could not allocate a port: {e}"))?;

    let port = listener.local_addr()
        .map_err(|e| format!("Could not read allocated port: {e}"))?
        .port();

    drop(listener);
    Ok(port)
}

#[tauri::command]
fn create_service_folder(
    name: String,
    language: String,
    framework: String,
) -> Result<String, String> {
    // Accept safe, lowercase service names only.
    if name.is_empty()
        || name.len() > 48
        || !name.as_bytes()[0].is_ascii_alphanumeric()
        || !name.as_bytes()[name.len() - 1].is_ascii_alphanumeric()
        || !name.chars().all(|c| {
            c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'
        })
    {
        return Err(
            "Invalid service name. Use lowercase letters, numbers, and hyphens."
                .into()
        );
    }

    let home = std::env::var_os("USERPROFILE")
        .or_else(|| std::env::var_os("HOME"))
        .ok_or_else(|| "Could not find the user's home directory".to_string())?;

    let app_dir = PathBuf::from(home).join("app");

    std::fs::create_dir_all(&app_dir)
        .map_err(|e| format!("Could not create app directory: {e}"))?;

    let service_dir = app_dir.join(&name);

    if service_dir.exists() {
        return Err(format!("A service named '{}' already exists.", name));
    }

    let (container_port, files, local_instructions): (
        u16,
        Vec<(&str, &str)>,
        &str,
    ) = match (language.as_str(), framework.as_str()) {

        // NODE.JS + EXPRESS
        ("Node.js", "Express") => (
            3000,
            vec![
                ("src/index.js", r#"
const express = require("express");

const app = express();
const port = Number(process.env.PORT) || 3000;

app.use(express.json());

app.get("/", (_req, res) => {
  res.json({
    service: "SERVICE_NAME",
    message: "API is running"
  });
});

app.get("/health", (_req, res) => {
  res.json({ status: "ok" });
});

app.listen(port, "0.0.0.0", () => {
  console.log(`SERVICE_NAME listening on port ${port}`);
});
"#),
                ("package.json", r#"
{
  "name": "SERVICE_NAME",
  "version": "1.0.0",
  "private": true,
  "description": "Microservice generated by Micronom",
  "main": "src/index.js",
  "scripts": {
    "start": "node src/index.js",
    "dev": "node --watch src/index.js"
  },
  "dependencies": {
    "express": "^5.1.0"
  }
}
"#),
                ("Dockerfile", r#"
FROM node:22-alpine
WORKDIR /app
COPY package.json ./
RUN npm install --omit=dev
COPY . .
ENV PORT=3000
EXPOSE 3000
CMD ["npm", "start"]
"#),
            ],
            "```powershell\nnpm install\nnpm run dev\n```",
        ),

        // PYTHON + FASTAPI
        ("Python", "FastAPI") => (
            8000,
            vec![
                ("app/main.py", r#"
import os
from fastapi import FastAPI

app = FastAPI(title="SERVICE_NAME")

@app.get("/")
async def root():
    return {
        "service": "SERVICE_NAME",
        "message": "API is running"
    }

@app.get("/health")
async def health():
    return {"status": "ok"}
"#),
                ("requirements.txt", r#"
fastapi>=0.115,<1.0
uvicorn[standard]>=0.34,<1.0
"#),
                ("Dockerfile", r#"
FROM python:3.12-slim
WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
ENV PORT=8000
EXPOSE 8000
CMD ["sh", "-c", "uvicorn app.main:app --host 0.0.0.0 --port ${PORT:-8000}"]
"#),
            ],
            "```powershell\npy -m venv .venv\n.venv\\Scripts\\Activate.ps1\npip install -r requirements.txt\nuvicorn app.main:app --reload --port 8000\n```",
        ),

        // GO + GIN
        ("Go", "Gin") => (
            8080,
            vec![
                ("main.go", r#"
package main

import (
    "net/http"
    "os"

    "github.com/gin-gonic/gin"
)

func main() {
    router := gin.Default()

    router.GET("/", func(c *gin.Context) {
        c.JSON(http.StatusOK, gin.H{
            "service": "SERVICE_NAME",
            "message": "API is running",
        })
    })

    router.GET("/health", func(c *gin.Context) {
        c.JSON(http.StatusOK, gin.H{
            "status": "ok",
        })
    })

    port := os.Getenv("PORT")
    if port == "" {
        port = "8080"
    }

    if err := router.Run(":" + port); err != nil {
        panic(err)
    }
}
"#),
                ("go.mod", r#"
module example.com/SERVICE_NAME

go 1.24

require github.com/gin-gonic/gin v1.10.0
"#),
                ("Dockerfile", r#"
FROM golang:1.24-alpine AS builder
WORKDIR /app
COPY go.mod ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -o server .

FROM alpine:3.21
WORKDIR /app
COPY --from=builder /app/server .
ENV PORT=8080
EXPOSE 8080
CMD ["./server"]
"#),
            ],
            "```powershell\ngo mod tidy\ngo run .\n```",
        ),

        // RUST + AXUM
        ("Rust", "Axum") => (
            3000,
            vec![
                ("src/main.rs", r#"
use axum::{routing::get, Json, Router};
use serde_json::{json, Value};
use std::net::SocketAddr;

async fn root() -> Json<Value> {
    Json(json!({
        "service": "SERVICE_NAME",
        "message": "API is running"
    }))
}

async fn health() -> Json<Value> {
    Json(json!({ "status": "ok" }))
}

#[tokio::main]
async fn main() {
    let app = Router::new()
        .route("/", get(root))
        .route("/health", get(health));

    let port: u16 = std::env::var("PORT")
        .unwrap_or_else(|_| "3000".to_string())
        .parse()
        .expect("PORT must be a valid port number");

    let address = SocketAddr::from(([0, 0, 0, 0], port));

    let listener = tokio::net::TcpListener::bind(address)
        .await
        .expect("Could not bind to port");

    println!("SERVICE_NAME listening on {}", address);

    axum::serve(listener, app)
        .await
        .expect("Server error");
}
"#),
                ("Cargo.toml", r#"
[package]
name = "SERVICE_NAME"
version = "0.1.0"
edition = "2021"

[dependencies]
axum = "0.8"
tokio = { version = "1", features = ["full"] }
serde_json = "1"
"#),
                ("Dockerfile", r#"
FROM rust:slim AS builder
WORKDIR /app
COPY Cargo.toml ./
COPY src ./src
RUN cargo build --release

FROM debian:bookworm-slim
WORKDIR /app
COPY --from=builder /app/target/release/SERVICE_NAME ./server
ENV PORT=3000
EXPOSE 3000
CMD ["./server"]
"#),
            ],
            "```powershell\ncargo run\n```",
        ),

        _ => {
            return Err("Unsupported language and framework combination.".into());
        }
    };

    let host_port = find_available_port()?;

    // Create the project directory only after validating the template.
    std::fs::create_dir(&service_dir)
        .map_err(|e| format!("Could not create service directory: {e}"))?;

    let result = (|| -> Result<(), String> {
        for (relative_path, contents) in &files {
            write_file(
                &service_dir,
                relative_path,
                &contents.replace("SERVICE_NAME", &name),
            )?;
        }

        let compose = format!(
            r#"services:
  {name}:
    build: .
    container_name: {name}
    ports:
      - "127.0.0.1:${{HOST_PORT}}:{container_port}"
    environment:
      PORT: "{container_port}"
    restart: unless-stopped
"#,
            name = name,
            container_port = container_port,
        );

        write_file(&service_dir, "docker-compose.yml", &compose)?;

        let env_file = format!(
            "HOST_PORT={}\nPORT={}\n",
            host_port,
            container_port
        );

        write_file(&service_dir, ".env", &env_file)?;

        write_file(
            &service_dir,
            ".gitignore",
            r#".env
node_modules/
.venv/
__pycache__/
*.pyc
target/
"#,
        )?;

        write_file(
            &service_dir,
            ".dockerignore",
            r#".git
.env
node_modules
.venv
__pycache__
*.pyc
target
"#,
        )?;

        let readme = format!(
            r#"# {name}

Generated by Micronom.

## Run locally

{local_instructions}

## Run with Docker

Make sure Docker Desktop is running.

```powershell
docker compose up --build -d
```

## Stop the service

```powershell
docker compose down
```

## API endpoints

- GET / - Service information
- GET /health - Health check

## Addresses

Local development: http://localhost:{container_port}

Docker: http://localhost:{host_port}

## Configuration

The `.env` file contains the host and container ports.

Change `HOST_PORT` in `.env` if the selected host port is already in use.
"#,
            name = name,
            local_instructions = local_instructions,
            container_port = container_port,
            host_port = host_port,
        );

        write_file(&service_dir, "README.md", &readme)?;

        Ok(())
    })();

    if let Err(error) = result {
        let _ = std::fs::remove_dir_all(&service_dir);
        return Err(error);
    }

    Ok(service_dir.to_string_lossy().into_owned())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .invoke_handler(tauri::generate_handler![create_service_folder])
        .setup(|app| {
            if cfg!(debug_assertions) {
                app.handle().plugin(
                    tauri_plugin_log::Builder::default()
                        .level(log::LevelFilter::Info)
                        .build(),
                )?;
            }

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while building tauri application");
}
